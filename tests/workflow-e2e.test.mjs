import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import fsSync from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import test from 'node:test';
import { fileURLToPath } from 'node:url';
import { STLManipulator } from '../dist/stl/stl-manipulator.js';
import { studioRetargeter } from '../dist/tuning/retarget.js';
import { studioSlicer } from '../dist/tuning/prepare-slice.js';
import { compareSliceScenarios } from '../dist/workflows/scenarios.js';
import { estimatePrintCost } from '../dist/workflows/cost.js';
import { createFitTest, extractObjects } from '../dist/workflows/geometry.js';
import { compareProjects } from '../dist/workflows/compare-projects.js';
const root = fileURLToPath(new URL('../', import.meta.url));
const slicerPath = [process.env.SLICER_PATH, '/Applications/BambuStudio.app/Contents/MacOS/BambuStudio', 'C:\\Program Files\\Bambu Studio\\bambu-studio.exe'].find(p => p && fsSync.existsSync(p));
test('real CLI compares process variants, estimates cost, extracts meshes and slices a fit socket without GUI', { skip: process.env.CI ? 'CI' : !slicerPath ? 'Bambu Studio CLI absent' : false, timeout: 300000 }, async (t) => {
    const dir = await fs.mkdtemp(path.join(os.tmpdir(), 'fatia-workflow-e2e-'));
    t.after(() => fs.rm(dir, { recursive: true, force: true }));
    const tempDir = path.join(dir, 'work'), outputDir = path.join(dir, 'outputs'), printerPreset = 'Bambu Lab X2D 0.4 nozzle';
    const manipulator = new STLManipulator(tempDir);
    const retarget = studioRetargeter({ slicerPath, tempDir, printerPreset, modelCode: 'X2D', manipulator });
    const base = await retarget(path.join(root, 'test/sample_cube.stl'));
    const file = path.join(dir, 'cube.3mf');
    await fs.writeFile(file, base.archive);
    const source = await fs.readFile(file);
    const result = await compareSliceScenarios({ path: file, scenarios: [{ name: 'standard', settings: { layer_height: .2 } }, { name: 'fine', settings: { layer_height: .16 } }], max_slices: 2 }, { printerPreset, tempDir, outputDir, slice: studioSlicer({ manipulator, slicerPath, printerPreset, modelCode: 'X2D', plateIndex: 0 }) });
    assert.equal(result.stop_reason, 'done');
    assert.equal(result.slices, 2);
    assert.ok(result.scenarios.every(s => s.status === 'measured'), JSON.stringify(result.scenarios));
    assert.ok(result.scenarios.every(s => s.time_s > 0 && s.weight_g > 0 && s.comparable), JSON.stringify(result.scenarios));
    assert.deepEqual(await fs.readFile(file), source);
    const cost = await estimatePrintCost({ path: file, material_price_per_kg: 100 });
    assert.ok(cost.per_project.material_cost > 0, JSON.stringify(cost));
    const extracted = await extractObjects({ file_path: file }, outputDir);
    assert.ok(extracted.objects.length > 0);
    const diff = await compareProjects({ project_a: file, project_b: result.scenarios[1].output_path });
    assert.ok(diff.changes.settings.some(c => c.key === 'layer_height'));
    const fit = await createFitTest({ gaps_mm: [.2] }, outputDir);
    const socket = fit.coupons[0].socket_path;
    assert.ok(socket, JSON.stringify(fit));
    const sliced = await retarget(socket);
    assert.ok(sliced.archive.length > 0);
    t.diagnostic(JSON.stringify({ scenarios: result.scenarios.map(s => ({ name: s.name, time_s: s.time_s, weight_g: s.weight_g })), cost: cost.per_project, fit: fit.coupons[0] }));
});
